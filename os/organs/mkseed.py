# Turiya: turn an organ's ELF into its seed, a C header Sakshi embeds and re-makes the organ from.
# usage: mkseed.py <elf> <NAME> <out.h>
import hashlib, sys

elf, name, out = sys.argv[1], sys.argv[2], sys.argv[3]
data = open(elf, "rb").read()
digest = hashlib.sha256(data).hexdigest()
with open(out, "w") as f:
    f.write("/* generated by organs/mkseed.py from %s - do not edit */\n" % elf.split("/")[-1])
    f.write('static const char %s_SHA256[] = "%s";\n' % (name, digest))
    f.write("static const unsigned long %s_LEN = %d;\n" % (name, len(data)))
    f.write("__attribute__((aligned(16))) static const unsigned char %s_SEED[] = {\n" % name)
    for i in range(0, len(data), 24):
        f.write(",".join(str(b) for b in data[i:i + 24]) + ",\n")
    f.write("};\n")
print(name, len(data), "bytes, sha256", digest)
